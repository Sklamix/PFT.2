import test, { after, before } from 'node:test'
import assert from 'node:assert/strict'
import { PrismaClient } from '@prisma/client'
import { assertClientIsTestDb, assertGateAllowsExecution, resolveObservabilityTestDb } from '../observability-db-gate'
import { createTestPrismaClient } from '../test-prisma-adapter'
import { beginTestPrismaInjection, endTestPrismaInjection } from '../test-prisma-injection'
import { createTelemetry, isValidTestRunId } from '../db-test-telemetry'

/**
 * PHASE 1.10.45 — admin login regression against a real database.
 *
 * GATED: requires OBSERVABILITY_TEST_DB=1 + OBSERVABILITY_TEST_DB_URL pointing
 * at the owner-approved isolated `pft_dbtest` database. Without both, every
 * test is reported as SKIP with an explicit reason.
 *
 * These tests WRITE users / rate-limit rows / audit rows to the test database
 * and require owner approval before the suite is run. They exercise the real
 * route, real password hashing, real limiter and real cookie issuance.
 */

process.env.ADMIN_SESSION_SECRET = 'phase-11045-auth-test-secret-0123456789'

const GATE = resolveObservabilityTestDb()
assertGateAllowsExecution(GATE)
const TEST_URL = GATE.action === 'use' ? GATE.url : null
const SKIP = TEST_URL ? false : `DB writes not authorized: ${GATE.action === 'use' ? '' : GATE.reason}`

const STRONG_PASSWORD = 'PFT-Test-Password!42'
const IP_HEADER = 'x-vercel-forwarded-for'
const TEST_IP = '203.0.113.45'

// PHASE 1.48: run-scoped identity. One TEST_RUN_ID per run (generated by the
// launcher) is embedded in every unique marker so records are attributable.
const RUN_ID = isValidTestRunId(process.env.TEST_RUN_ID) ? process.env.TEST_RUN_ID : null
const RUN_TAG = RUN_ID ?? Date.now().toString(36)
const TELEMETRY = createTelemetry(RUN_ID, 'auth-login-db')
TELEMETRY.suiteStarted()

type Post = (request: Request) => Promise<Response>

let prisma: PrismaClient | null = null
let post: Post
let hashPassword: (password: string) => Promise<string>
let adminCookie: string
const createdUserIds: string[] = []
const createdEmails: string[] = []
const createdIps = new Set<string>([TEST_IP])

before(async () => {
  if (!TEST_URL) return
  const client = createTestPrismaClient(TEST_URL).prisma
  prisma = await assertClientIsTestDb(client)
  // Route/app modules must use the TLS-verified adapter client, not a global
  // DATABASE_URL client. Injection is TEST-only and cleared in `after`.
  beginTestPrismaInjection(prisma)

  const auth = await import('../../lib/admin/auth')
  hashPassword = auth.hashPassword
  adminCookie = auth.ADMIN_COOKIE
  post = (await import('../../app/api/admin/auth/login/route')).POST
})

after(async () => {
  if (!prisma) { TELEMETRY.suiteCompleted(); return }
  const counts: Record<string, number> = {}
  const bucketWhere = {
    OR: [
      ...createdEmails.map((email) => ({ key: { contains: email } })),
      ...[...createdIps].map((ip) => ({ key: { equals: `ip:${ip}` } })),
    ],
  }
  try {
    // PHASE 1.50: authoritative creation snapshot (rows created by the shared
    // rate limiter / activity log cannot be attributed per call without touching
    // production code). User creations are already emitted at the create point.
    const createdSnap: Record<string, number> = {
      RateLimitBucket: await prisma.rateLimitBucket.count({ where: bucketWhere }),
    }
    if (createdUserIds.length) {
      createdSnap.AuditLog = await prisma.auditLog.count({ where: { actorId: { in: createdUserIds } } })
    }
    TELEMETRY.snapshotCreated(createdSnap)

    TELEMETRY.cleanupStarted()
    const bucketRes = await prisma.rateLimitBucket.deleteMany({ where: bucketWhere })
    counts.RateLimitBucket = bucketRes.count
    if (createdUserIds.length) {
      const auditRes = await prisma.auditLog.deleteMany({ where: { actorId: { in: createdUserIds } } })
      counts.AuditLog = auditRes.count
      const userRes = await prisma.user.deleteMany({ where: { id: { in: createdUserIds } } })
      counts.User = userRes.count
    }
    TELEMETRY.cleanupCompleted(counts)
  } catch (error) {
    TELEMETRY.cleanupFailed(counts, error)
    throw error // a real cleanup failure must fail the run, never be hidden
  } finally {
    endTestPrismaInjection()
    try { await prisma.$disconnect() } catch (error) {
      console.error('auth-login-db cleanup: disconnect failed: ' + String((error as Error)?.message ?? error))
    }
  }
  TELEMETRY.suiteCompleted()
})

let counter = 0
async function createStaff(role: 'ADMIN' | 'SUPPORT' | 'RISK_MANAGER' | 'TRADER') {
  const email = `phase11045-${role.toLowerCase()}-${RUN_TAG}-${Date.now().toString(36)}-${counter++}@test.local`
  const user = await prisma!.user.create({
    data: { email, passwordHash: await hashPassword(STRONG_PASSWORD), name: `P11045 ${role}`, role },
    select: { id: true, email: true },
  })
  TELEMETRY.recordCreated('User')
  createdUserIds.push(user.id)
  createdEmails.push(email.toLowerCase())
  return user
}

function loginRequest(email: string, password: string, ip = TEST_IP) {
  createdIps.add(ip)
  return new Request('http://localhost:3100/api/admin/auth/login', {
    method: 'POST',
    headers: { 'content-type': 'application/json', [IP_HEADER]: ip },
    body: JSON.stringify({ email, password }),
  })
}

function bucketKey(email: string) {
  return `email:${email.trim().toLowerCase()}`
}

test('wrong password returns 401 and increments the failure counter', { skip: SKIP }, async () => {
  const user = await createStaff('SUPPORT')
  const response = await post(loginRequest(user.email, 'wrong-password'))
  assert.equal(response.status, 401)
  assert.equal(response.headers.get('set-cookie'), null, 'failed login must not issue a session')

  const bucket = await prisma!.rateLimitBucket.findUnique({ where: { key: bucketKey(user.email) } })
  assert.equal(bucket?.count, 1)
  assert.ok(bucket?.updatedAt instanceof Date, 'updatedAt must be written (23502 regression)')
})

test('repeated failures trigger 429 with Retry-After and keep counting stable', { skip: SKIP }, async () => {
  const user = await createStaff('SUPPORT')
  const ip = '203.0.113.46'
  for (let attempt = 1; attempt <= 5; attempt += 1) {
    const response = await post(loginRequest(user.email, 'wrong-password', ip))
    assert.equal(response.status, 401, `attempt ${attempt}`)
  }

  const locked = await post(loginRequest(user.email, STRONG_PASSWORD, ip))
  assert.equal(locked.status, 429, 'the 6th attempt must be blocked even with the correct password')
  const retryAfter = Number(locked.headers.get('retry-after'))
  assert.ok(Number.isFinite(retryAfter) && retryAfter > 0, 'Retry-After must be present')

  const bucket = await prisma!.rateLimitBucket.findUnique({ where: { key: bucketKey(user.email) } })
  // PHASE 1.99: the reservation is taken BEFORE the credential check, so the
  // refused attempt is counted as well. The counter saturates at limit+1
  // (5 -> 6) and never grows beyond that inside the window.
  assert.equal(bucket?.count, 6, 'a refused attempt is counted; the counter saturates at limit+1')
})

test('unknown email returns a generic 401 and does not leak existence', { skip: SKIP }, async () => {
  const email = `phase11045-missing-${RUN_TAG}-${Date.now()}@test.local`
  createdEmails.push(email)
  const response = await post(loginRequest(email, 'whatever', '203.0.113.47'))
  assert.equal(response.status, 401)
  assert.equal(response.headers.get('set-cookie'), null)
})

test('a TRADER account cannot log into the admin desk', { skip: SKIP }, async () => {
  const user = await createStaff('TRADER')
  const response = await post(loginRequest(user.email, STRONG_PASSWORD, '203.0.113.48'))
  assert.equal(response.status, 401, 'staff lookup filters non-staff roles')
  assert.equal(response.headers.get('set-cookie'), null)
})

test('correct credentials issue a hardened session cookie and clear failures', { skip: SKIP }, async () => {
  const user = await createStaff('ADMIN')
  const ip = '203.0.113.49'

  const wrong = await post(loginRequest(user.email, 'wrong-password', ip))
  assert.equal(wrong.status, 401)

  const ok = await post(loginRequest(user.email, STRONG_PASSWORD, ip))
  assert.equal(ok.status, 200)
  const body = (await ok.json()) as { user?: { role?: string } }
  assert.equal(body.user?.role, 'ADMIN')

  const cookie = ok.headers.get('set-cookie') ?? ''
  assert.ok(cookie.includes(adminCookie), 'session cookie must be set')
  assert.match(cookie.toLowerCase(), /httponly/)
  assert.match(cookie.toLowerCase(), /samesite=lax/)

  const bucket = await prisma!.rateLimitBucket.findUnique({ where: { key: bucketKey(user.email) } })
  assert.equal(bucket, null, 'successful login resets the email counter')
})
